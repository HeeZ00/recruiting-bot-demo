/** 자격격 조사: 받침 있으면 '으로서', 없으면 '로서' (한글 아니면 기본 '로서') */
function roleJosa(word: string): string {
  const last = word.trim().slice(-1);
  const code = last.charCodeAt(0);
  if (code < 0xac00 || code > 0xd7a3) return "로서";
  return (code - 0xac00) % 28 !== 0 ? "으로서" : "로서";
}

/** JD 텍스트에서 직무명 추출 (직무명 라벨 → 첫 굵은글씨 → 첫 줄 순으로 시도) */
function roleFromJD(jd: string): string {
  const byLabel = jd.match(/(?:담당\s*)?(?:직무명?|포지션명?)\s*[:：]\s*(.+)/);
  if (byLabel) return byLabel[1].split(/[\n(]/)[0].trim();
  const byBold = jd.match(/\*\*(.+?)\*\*/);
  if (byBold) return byBold[1].trim();
  const first = jd.split(/\r?\n/).map((l) => l.trim()).find(Boolean);
  return first ? first.replace(/^#+\s*/, "").slice(0, 20) : "이 포지션";
}

